/**
 * Response shapes of the Murmur REST API (what the client receives).
 * The mock server builds them from its records in `api/server.ts`.
 */

import type { Ionicons } from '@expo/vector-icons';

export type IconName = React.ComponentProps<typeof Ionicons>['name'];

export type User = {
  id: string;
  name: string;
  handle: string;
  color: string;
  bio: string;
  followers: number;
  following: number;
  /** Whether the signed-in user follows this user. */
  isFollowed: boolean;
};

export type Media = { color: string; icon: IconName; aspect: number };

export type Poll = {
  options: { label: string; votes: number }[];
  days: number;
  /** Option chosen by the signed-in user, or null. */
  votedOption: number | null;
};

export type Post = {
  id: string;
  author: User;
  text: string;
  createdAt: number;
  media?: Media;
  poll?: Poll;
  likeCount: number;
  liked: boolean;
  repostCount: number;
  replyCount: number;
  replyTo?: string;
};

export type NewPost = {
  text: string;
  media?: Media;
  poll?: { options: string[]; days: number };
};

export type Page<T> = { items: T[]; nextCursor: string | null };

export type FeedTab = 'for_you' | 'following';

export type Notice = {
  id: string;
  kind: 'like' | 'follow' | 'reply' | 'repost' | 'mention';
  user: User;
  postId?: string;
  postText?: string;
  createdAt: number;
  read: boolean;
};

export type Message = {
  id: string;
  /** Id generated by the client, used to deduplicate retried sends. */
  clientId?: string;
  from: string;
  text: string;
  createdAt: number;
  /** Client-only: set while a send is in flight or after it failed. */
  status?: 'sending' | 'failed';
};

export type ConversationSummary = {
  id: string;
  user: User;
  lastMessage: Message | null;
  unread: number;
  typing: boolean;
  updatedAt: number;
};

export type Thread = { conversation: ConversationSummary; messages: Message[] };

export type LiveSession = { id: string; title: string; startedAt: number; viewers: number; endedAt?: number };

export type Trend = { tag: string; posts: string };
